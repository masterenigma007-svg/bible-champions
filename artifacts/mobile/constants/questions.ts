export function getQuestionsByCategory(category: Category, difficulty: Difficulty, count: number = 10): Question[] {
  const filtered = QUESTIONS.filter(
    (q) => q.category === category && q.difficulty === difficulty
  );
  const shuffled = [...filtered].sort(() => Math.random() - 0.5);
  if (shuffled.length < count) {
    const extras = QUESTIONS.filter(
      (q) => q.category === category && q.difficulty !== difficulty
    ).sort(() => Math.random() - 0.5);
    return [...shuffled, ...extras].slice(0, count);
  }
  return shuffled.slice(0, count);
}

export function getRandomQuestions(count: number = 10): Question[] {
  const shuffled = [...QUESTIONS].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
}
